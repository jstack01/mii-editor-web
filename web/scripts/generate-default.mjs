import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const sourceRelative = 'EXTRACTED-SWF/classicGUI.swf/scripts/mii/authoring/ClassicGUI.as';
const source = readFileSync(new URL(`../../${sourceRelative}`, import.meta.url));
const matches = [...source.toString('utf8').matchAll(/public var hexData:String = "([0-9a-f]{148})";/g)];
if (matches.length !== 1) throw new Error('Expected exactly one original default hex literal.');
const hash = createHash('sha256').update(source).digest('hex');
const text = `// Generated by scripts/generate-default.mjs. Do not hand-edit.\n// Source: ${sourceRelative}\n// SHA-256: ${hash}\nexport const DEFAULT_MII_HEX = '${matches[0][1]}';\n`;
const target = new URL('../src/generated/default-character.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) throw new Error('Default fixture is stale; run the dev or build command to regenerate.');
} else {
  mkdirSync(fileURLToPath(new URL('../src/generated/', import.meta.url)), { recursive: true });
  writeFileSync(target, text);
}

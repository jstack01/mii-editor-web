// Read-only extraction of original schema/order. Runtime code never fetches AS3.
import './generate-default.mjs';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const sourcePath = 'EXTRACTED-SWF/classicGUI.swf/scripts/mii/MiiCharacterData.as';
const bytes = readFileSync(new URL(`../../${sourcePath}`, import.meta.url));
const source = bytes.toString('utf8');
const constants = Object.fromEntries([...source.matchAll(/public static const (\w+):int = (\d+);/g)].map((m) => [m[1], Number(m[2])]));
const fields = {};
for (const match of source.matchAll(/defineValue\("(\w+)",([^;]+)\);/g)) {
  const args = match[2].split(',').map((value) => value.trim());
  const [word, shift, width = 1, min = 0, declaredMax = 0] = args.map((value) => constants[value] ?? Number(value));
  fields[match[1]] = { word, shift, width, min, max: declaredMax || 2 ** width - 1 };
}
const order = JSON.parse(source.match(/valueNames:Array = (\[[^;]+\]);/)[1]);
const tableSource = source.match(/valueToFrameLookup:Object = (\{[\s\S]*?\});/)[1];
const tables = JSON.parse(tableSource);
if (Object.keys(fields).length !== 45 || order.length !== 45 || Object.keys(tables).length !== 5 || !order.every((name) => fields[name])) throw new Error('Source schema changed; inspect extraction before proceeding.');
const hash = createHash('sha256').update(bytes).digest('hex');
const text = `// Generated by scripts/generate-source-data.mjs. Do not hand-edit.\n// Source: ${sourcePath}\n// SHA-256: ${hash}\nexport const MII_FIELDS = ${JSON.stringify(fields, null, 2)} as const;\nexport type NumericField = keyof typeof MII_FIELDS;\nexport const MII_VALUE_NAMES = Object.freeze(${JSON.stringify(order)} as const);\nexport const MII_PERMUTATIONS = Object.freeze({\n${Object.entries(tables).map(([key, values]) => `  ${key}: Object.freeze(${JSON.stringify(values)} as const),`).join('\n')}\n});\nObject.values(MII_FIELDS).forEach(Object.freeze);\nObject.freeze(MII_FIELDS);\n`;
const target = new URL('../src/generated/mii-schema.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) throw new Error('Source schema fixture is stale; run dev or build to regenerate.');
} else {
  mkdirSync(fileURLToPath(new URL('../src/generated/', import.meta.url)), { recursive: true });
  writeFileSync(target, text);
}

if (process.argv.includes('--manifest')) {
  const path = new URL('../../evidence/phase2/schema.json', import.meta.url);
  mkdirSync(fileURLToPath(new URL('../../evidence/phase2/', import.meta.url)), { recursive: true });
  const sourceHashes = {};
  for (const relative of [sourcePath, 'EXTRACTED-SWF/classicGUI.swf/scripts/mii/values/MiiDataValue.as', 'EXTRACTED-SWF/classicGUI.swf/scripts/mii/values/Range.as']) {
    sourceHashes[relative] = createHash('sha256').update(readFileSync(new URL(`../../${relative}`, import.meta.url))).digest('hex');
  }
  writeFileSync(path, JSON.stringify({ sourceHashes, fields, valueNames: order, valueToFrameLookup: tables }, null, 2) + '\n');
}
